void Print(const Student* p, const int N, const string specialityStr[])
{
    SetConsoleOutputCP(65001);                                      // гарантуємо кодування UTF-8 для виводу таблиці
    SetConsoleCP(65001);                                            // гарантуємо кодування UTF-8 для консолі

    const string line(91, '=');                                     // створюємо рядок із 91 символу '=' для верхньої та нижньої межі таблиці
    const string dash(91, '-');                                     // створюємо рядок із 91 символу '-' для розділення шапки і даних

    cout << "Таблиця успішності студентів:" << endl;                // виводимо заголовок таблиці
    cout << line << endl;                                           // друкуємо верхню рамку таблиці
    cout << "| № |    Прізвище    | Курс |      Спеціальність      | Фізика | Математика | Інформатика |" << endl; // друкуємо назви стовпців
    cout << dash << endl;                                           // друкуємо розділювач під шапкою таблиці

    for (int i = 0; i < N; i++)                                     // проходимо по кожному студенту в масиві p
    {
        int lenP = 0;                                               // лічильник реальної кількості символів (літер) у прізвищі
        for (unsigned char c : p[i].prizv)                          // перебираємо кожен байт рядка з прізвищем
            if ((c & 0xC0) != 0x80) lenP++;                         // рахуємо тільки початкові байти символів UTF-8 (ігноруємо байти-продовження 10xxxxxx)

        int lenS = 0;                                               // лічильник реальної кількості символів у назві спеціальності
        for (unsigned char c : specialityStr[p[i].speciality])      // перебираємо кожен байт назви спеціальності
            if ((c & 0xC0) != 0x80) lenS++;                         // збільшуємо лічильник на 1 для кожного символу, щоб кирилиця не збивала ширину колонки

        cout << "| " << setw(1) << right << i + 1                   // виводимо порядковий номер студента (i + 1)
            << " | " << p[i].prizv << string(lenP < 14 ? 14 - lenP : 0, ' ') // виводимо прізвище і добиваємо пробілами до ширини 14 символів
            << " | " << setw(4) << right << p[i].kurs               // виводимо курс, вирівняний по правому краю в полі шириною 4
            << " | " << specialityStr[p[i].speciality] << string(lenS < 23 ? 23 - lenS : 0, ' ') // виводимо спеціальність і добиваємо пробілами до 23 символів
            << " | " << setw(6) << right << p[i].fizyka             // виводимо оцінку з фізики у полі шириною 6
            << " | " << setw(10) << right << p[i].matematyka        // виводимо оцінку з математики у полі шириною 10
            << " | " << setw(11) << right << p[i].informatyka       // виводимо оцінку з інформатики у полі шириною 11
            << " |" << endl;                                        // закриваємо рядок таблиці і переходимо на новий рядок
    }
    cout << line << endl << endl;                                   // друкуємо нижню рамку таблиці та порожній рядок після неї
}

int Sum(const Student& s)
{
    return s.fizyka + s.matematyka + s.informatyka;                 // додаємо три оцінки студента s і повертаємо точну цілу суму
}

double Average(const Student& s)
{
    return Sum(s) / 3.0;                                            // ділимо суму оцінок на 3.0 (дійсне число, щоб отримати дробовий результат)
}

void Sort(Student* p, const int N)                                                                                                                                  //детальніше
{
    Student tmp;                                                    // тимчасова структура для обміну двох студентів місцями
    for (int i0 = 0; i0 < N - 1; i0++)                              // зовнішній цикл сортування бульбашкою (кількість проходів N-1)
        for (int i1 = 0; i1 < N - i0 - 1; i1++)                     // внутрішній цикл порівняння сусідніх елементів p[i1] і p[i1 + 1]
            if ((Sum(p[i1]) > Sum(p[i1 + 1]))                       // умова 1: якщо сума балів лівого більша за правого (сортуємо за зростанням балу)
                ||                                                  // АБО
                (Sum(p[i1]) == Sum(p[i1 + 1]) &&                    // умова 2: якщо бали однакові, але
                    p[i1].prizv < p[i1 + 1].prizv)                  // прізвище лівого менше за алфавітом (сортуємо прізвища за СПАДАННЯМ)
                ||                                                  // АБО
                (Sum(p[i1]) == Sum(p[i1 + 1]) &&                    // умова 3: якщо і бали однакові,
                    p[i1].prizv == p[i1 + 1].prizv &&               // і прізвища однакові, але
                    p[i1].kurs > p[i1 + 1].kurs))                   // курс лівого більший за правого (сортуємо курс за зростанням)
            {
                tmp = p[i1];                                        // зберігаємо лівого студента у тимчасову змінну tmp
                p[i1] = p[i1 + 1];                                  // записуємо правого студента на місце лівого
                p[i1 + 1] = tmp;                                    // записуємо збереженого лівого студента на місце правого
            }
}

int* IndexSort(const Student* p, const int N)                                                                                                               //детальніше
{
    int* I = new int[N];                                            // виділяємо динамічну пам'ять під індексний масив розміром N
    for (int k = 0; k < N; k++)                                     // цикл ініціалізації індексного масиву
        I[k] = k;                                                   // заповнюємо початковими індексами 0, 1, 2, ..., N-1

    int i, j, value;                                                // оголошуємо лічильники циклів i, j та змінну value для поточного індексу
    for (i = 1; i < N; i++)                                         // цикл сортування вставкою, починаючи з другого елемента (i = 1)
    {
        value = I[i];                                               // запам'ятовуємо індекс студента, для якого шукаємо правильну позицію
        for (j = i - 1;                                             // починаємо перевіряти вже відсортовану частину ліворуч (з i - 1)
            j >= 0 && ((Sum(p[I[j]]) > Sum(p[value])) ||            // поки не дійшли до початку і студент I[j] має більший бал за value
                (Sum(p[I[j]]) == Sum(p[value]) &&                   // АБО бали рівні, і
                    p[I[j]].prizv > p[value].prizv) ||              // прізвище I[j] більше за алфавітом (тут прізвища за ЗРОСТАННЯМ)
                (Sum(p[I[j]]) == Sum(p[value]) &&                   // АБО бали рівні,
                    p[I[j]].prizv == p[value].prizv &&              // прізвища рівні, і
                    p[I[j]].kurs > p[value].kurs));                 // курс I[j] більший за курс value
            j--)                                                    // рухаємося вліво по масиву індексів
        {
            I[j + 1] = I[j];                                        // зсуваємо більший індекс на одну позицію вправо, звільняючи місце
        }
        I[j + 1] = value;                                           // вставляємо збережений індекс value на знайдене місце
    }
    return I;                                                       // повертаємо вказівник на сформований індексний масив
}

