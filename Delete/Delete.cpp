int BinSearch(const Student* p, const int N, const string& prizv, const int kurs, const double avg)
{
    const double eps = 0.005;                                       // задаємо похибку (допуск) для порівняння дробових середніх балів
    int L = 0, R = N - 1, m;                                        // L — ліва межа пошуку (0), R — права межа (N-1), m — індекс середини
    do {                                                            // цикл бінарного пошуку, який ділить діапазон навпіл на кожному кроці
        m = (L + R) / 2;                                            // обчислюємо індекс середнього елемента поточного відрізка [L, R]
        double am = Average(p[m]);                                  // обчислюємо реальний середній бал середнього студента p[m]
        bool sameAvg = fabs(am - avg) < eps;                        // перевіряємо, чи збігається середній бал p[m] із шуканим avg з точністю eps
        if (sameAvg && p[m].prizv == prizv && p[m].kurs == kurs)    // якщо одночасно збіглися середній бал, прізвище та курс
            return m;                                               // повертаємо індекс m знайденого студента і завершуємо пошук
        if ((!sameAvg && am < avg) ||                               // якщо середній бал p[m] менший за шуканий (він стоїть лівіше у відсортованому масиві)
            (sameAvg && p[m].prizv > prizv) ||                      // АБО бали рівні, а прізвище p[m] більше (бо в Sort() прізвища йдуть за спаданням)
            (sameAvg && p[m].prizv == prizv && p[m].kurs < kurs))   // АБО бали й прізвища рівні, а курс p[m] менший за шуканий
        {
            L = m + 1;                                              // відкидаємо ліву половину разом із серединою: шукаємо праворуч від m
        }
        else                                                        // у всіх інших випадках шуканий студент може бути лише лівіше за m
        {
            R = m - 1;                                              // відкидаємо праву половину разом із серединою: шукаємо ліворуч від m
        }
    } while (L <= R);                                               // продовжуємо пошук, поки ліва межа не перетне праву
    return -1;                                                      // якщо межі зійшлися, а збігу не було — повертаємо -1 (студента не знайдено)
}